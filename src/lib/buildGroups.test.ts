import { expect, test } from 'bun:test'
import { groupTree, normalizeGroup } from './buildGroups'

test('вложенные группы сборок — деревом, родитель перед детьми', () => {
  const rows = groupTree(['Моды/Тест', 'Ванилла', 'Моды', 'Моды/Альфа/Глубже'])
  expect(rows.map((r) => r.path), 'родитель стоит перед своими подгруппами, соседи по алфавиту').toEqual(['Ванилла', 'Моды', 'Моды/Альфа', 'Моды/Альфа/Глубже', 'Моды/Тест'])
  expect(rows.find((r) => r.path === 'Моды/Альфа')?.depth, 'промежуточная группа появляется, даже если сборок в ней нет').toBe(1)
  expect(rows.find((r) => r.path === 'Моды/Тест')?.label, 'подпись — последнее звено пути').toBe('Тест')
})

test('лишние пробелы и пустые звенья не плодят двойников', () => {
  expect(normalizeGroup(' Моды / / Тест '), 'тот же путь, что и «Моды/Тест»').toBe('Моды/Тест')
  expect(normalizeGroup('///'), 'пустой путь — без группы').toBe('')
})
