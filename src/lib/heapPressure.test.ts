import { describe, expect, it } from 'bun:test'
import { heapEventDue } from './heapPressure'

// Вход (заполнение кучи, время с прошлого отчёта, был ли уже тревожный) → вердикт.
// Отчёты о памяти нужны, чтобы отличить утечку в интерфейсе от машины, у которой
// память кончилась сама: без них падение рендерера выглядит одинаково в обоих случаях.
describe('когда лаунчер шлёт замер памяти', () => {
  it('куча у потолка отчитывается сразу — это состояние, в котором рендерер умирает', () => {
    expect(heapEventDue(85, 0, false)).toBe('high')
  })

  it('тревожный отчёт уходит один раз за сессию: иначе висящая под потолком куча зальёт телеметрию', () => {
    expect(heapEventDue(85, 0, true)).toBe(null)
  })

  it('спокойная куча молчит до планового часа — замер раз в минуту не должен ничего слать', () => {
    expect(heapEventDue(20, 60_000, false)).toBe(null)
  })

  it('через час уходит плановый замер: по нему видно, растёт ли сессия', () => {
    expect(heapEventDue(20, 3_600_000, false)).toBe('routine')
  })

  it('после тревожного отчёта плановые продолжают идти — рост нужно видеть и дальше', () => {
    expect(heapEventDue(85, 3_600_000, true)).toBe('routine')
  })
})
