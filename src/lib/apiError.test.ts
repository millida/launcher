import { expect, test } from 'bun:test'
import { apiErrorText } from './apiError'

// Вход → вердикт. Закреплено потому, что «Друзья» показывали «войди в аккаунт»
// на любую неудачу: игрок с живой сессией шёл чинить вход вместо ника.
const cases: Array<[string, unknown, string]> = [
  ['объяснение сервера доходит как есть', new Error('Игрок с таким ником не найден'), 'Игрок с таким ником не найден'],
  ['мёртвая сессия названа сессией', new Error('unauthorized'), 'Сессия Millida закончилась — войди в аккаунт заново'],
  ['401 — тоже про вход', new Error('http 401'), 'Сессия Millida закончилась — войди в аккаунт заново'],
  ['частые запросы — это ожидание, а не вход', new Error('http 429'), 'Слишком много попыток подряд — подожди немного и повтори'],
  ['английский шум троттлера не доезжает до игрока', new Error('ThrottlerException: Too Many Requests'), 'Слишком много попыток подряд — подожди немного и повтори'],
  ['отказ прав назван отказом', new Error('http 403'), 'Millida отказала в этом действии'],
  ['пропажа названа пропажей', new Error('http 404'), 'Не найдено — возможно, это уже удалено'],
  ['занятое значение объясняется', new Error('http 409'), 'Занято — выбери другое значение'],
  ['таймаут назван таймаутом', new Error('operation timed out'), 'Millida не ответила вовремя — повтори попытку'],
  ['обрыв связи назван обрывом', new Error('error sending request for url'), 'Нет связи с Millida — проверь интернет и повтори'],
  ['удержанное сообщение объясняет правило', new Error('off-platform: контакты вне площадки запрещены'), 'контакты вне площадки запрещены'],
  ['сбой сервера объясняется, а не показывается кодом', new Error('http 500'), 'Сбой на стороне Millida — повтори через минуту'],
  ['неизвестный код дополняется задачей', new Error('http 418'), 'Не удалось отправить заявку (http 418)'],
  ['пустая ошибка не оставляет игрока без текста', new Error(''), 'Не удалось отправить заявку'],
]

for (const [name, error, want] of cases) {
  test(name, () => {
    expect(apiErrorText(error, 'Не удалось отправить заявку')).toBe(want)
  })
}
